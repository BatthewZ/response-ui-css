#!/usr/bin/env node
// theme-from-json.mjs — generate a theme CSS file from JSON exported by ThemeEditor.
//
// Usage:
//   theme-from-json my-theme.json --name aurora > themes/aurora.css
//   theme-from-json my-theme.json --selector ':root[data-theme="aurora"]'
//
// Input shape (loose; only `vars` is required):
//   {
//     "name": "aurora",
//     "selector": ":root[data-theme=\"aurora\"]",   // optional, derived from name
//     "colorScheme": "dark",                          // optional
//     "vars": {
//       "--C-CANVAS": "oklch(...)",
//       "--C-PRIMARY": "oklch(...)",
//       ...
//     }
//   }

import { readFileSync } from "node:fs";
import { argv, exit, stderr, stdout } from "node:process";

function parseArgs(args) {
  const out = { _: [] };
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === "--name") out.name = args[++i];
    else if (a === "--selector") out.selector = args[++i];
    else if (a === "--help" || a === "-h") out.help = true;
    else out._.push(a);
  }
  return out;
}

const HELP = `theme-from-json — emit a CSS theme file from JSON

Usage:
  theme-from-json <input.json> [--name <slug>] [--selector <css-selector>]

If --selector is omitted, ':root[data-theme="<name>"]' is used.
If --name is omitted, the JSON's "name" field is used; otherwise "custom".
`;

const args = parseArgs(argv.slice(2));
if (args.help || args._.length === 0) {
  stdout.write(HELP);
  exit(args.help ? 0 : 1);
}

const inputPath = args._[0];
let json;
try {
  json = JSON.parse(readFileSync(inputPath, "utf8"));
} catch (err) {
  stderr.write(`Failed to read JSON: ${err.message}\n`);
  exit(1);
}

const name = args.name ?? json.name ?? "custom";
const selector = args.selector ?? json.selector ?? `:root[data-theme="${name}"]`;
const colorScheme = json.colorScheme ?? json.color_scheme ?? null;
const vars = json.vars ?? json.variables ?? json.tokens ?? null;

if (!vars || typeof vars !== "object") {
  stderr.write(`Input JSON is missing a "vars" object.\n`);
  exit(1);
}

const lines = [];
lines.push(`/* Generated by @batthewz/response-ui-css/theme-from-json — ${name} */`);
lines.push("");
lines.push(`${selector} {`);
if (colorScheme) lines.push(`  color-scheme: ${colorScheme};`);
for (const [key, value] of Object.entries(vars)) {
  const prop = key.startsWith("--") ? key : `--${key}`;
  lines.push(`  ${prop}: ${value};`);
}
lines.push(`}`);
lines.push("");

stdout.write(lines.join("\n"));
